const assert = require('assert');
const fs = require('fs');
const server = fs.readFileSync('server.js', 'utf8');
const admin = fs.readFileSync('admin.js', 'utf8');
assert(require('../lib/pagination').positiveInteger('1e2',50,200)===50, 'La paginación debe rechazar números ambiguos');
assert(server.includes('const countValues = values.slice(0, -2);'), 'El total debe poder calcularse en páginas vacías');
